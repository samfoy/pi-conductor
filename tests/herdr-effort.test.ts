import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { sandboxPi } from "./helpers/tmp.ts";
import { gitTestEnv } from "./helpers/git-env.ts";
import { herdrFixture } from "./helpers/herdr-pipeline.ts";
import { createWorktree } from "../src/worktree.ts";
import { createRunPipeline } from "../src/run-pipeline.ts";
import { openEffort } from "../src/effort/open.ts";
import { addEffortMember } from "../src/effort/store.ts";
sandboxPi();
const git = (cwd: string, ...args: string[]) => execFileSync("git", args, { cwd, env: gitTestEnv(), encoding: "utf8", stdio: "pipe" }).trim();
test("H7 effort child exit -> hook -> hooked candidate -> verify -> CAS -> shared settle; workspace/pane retained", { timeout: 15000 }, async t => {
  const h = herdrFixture("held"), root = h.run.cwd, evidence = join(root, h.run.id);
  git(root, "init", "-b", "main"); git(root, "config", "user.name", "Fixture"); git(root, "config", "user.email", "fixture@example.test");
  const policyLog = join(evidence, "policy.log"), hook = join(evidence, "hook-passed"), verifying = join(evidence, "verifying"), release = join(evidence, "release");
  mkdirSync(join(root, ".githooks"));
  writeFileSync(join(root, ".githooks", "pre-commit"), `#!/bin/sh\nprintf 'policy\\n' >> '${policyLog}'\n`, { mode: 0o755 });
  git(root, "config", "core.hooksPath", ".githooks");
  writeFileSync(join(root, "base"), "base"); writeFileSync(join(root, ".gitignore"), ".worktrees/\noracle-h7/\n");
  git(root, "add", "base", ".gitignore", ".githooks/pre-commit"); git(root, "commit", "-m", "base");
  const base = git(root, "rev-parse", "HEAD"), index = readFileSync(join(root, ".git", "index"));
  const effort = openEffort(root, "h7", "owner", { verify: `if test -f change; then test -f '${hook}' || exit 1; touch '${verifying}'; while ! test -f '${release}'; do sleep 0.02; done; fi` });
  addEffortMember(effort, h.run.id);
  const path = join(root, ".worktrees", "conductor-wt", h.run.id);
  createWorktree({ gitRoot: root, worktreePath: path, branch: "writer" }, { from: base });
  writeFileSync(join(path, "change"), "verified change"); git(path, "add", "change"); git(path, "commit", "-m", "change");
  const policyBefore = readFileSync(policyLog, "utf8");
  Object.assign(h.run, { parentSessionId: "owner", worktreePath: path, worktreeBranch: "writer", worktreeBaseBranch: "main",
    effort: { owner: effort.owner, name: "h7", gitRoot: root, role: "writer", spawnBase: base, touches: ["change"] } });
  let completions = 0, doneResolved = false;
  h.onSleep(() => { assert.equal(existsSync(hook), false, "unsafe hook before child exit"); assert.equal(git(root, "rev-parse", effort.intRef), base); h.exit(); });
  const done = createRunPipeline(h.run, [], { ...h.opts, cwd: path, resolvedHook: { command: `touch '${hook}'`, timeoutSeconds: 5, source: "per-call" }, onComplete: () => completions++ });
  void done.then(() => { doneResolved = true; });
  t.after(async () => { writeFileSync(release, "release"); await done; });
  await new Promise<void>(resolve => { const timer = setInterval(() => { if (existsSync(verifying)) { clearInterval(timer); resolve(); } }, 10); t.after(() => clearInterval(timer)); });
  assert.equal(h.gone(), true); assert.equal(h.run.hookResult?.passed, true); assert.equal(h.run.status, "integrating");
  assert.equal(doneResolved, false); assert.equal(completions, 0); assert.equal(existsSync(h.run.finalPath), false);
  assert.equal(git(root, "rev-parse", effort.intRef), base, "no integration before verify/CAS");
  assert.ok(readFileSync(policyLog, "utf8").length > policyBefore.length, "candidate commit ran repository hook");
  writeFileSync(release, "release"); await done;
  assert.equal(h.run.status, "completed", h.run.errorMessage); assert.equal(h.run.integration?.delivery, "attempted"); assert.equal(completions, 1);
  assert.equal(git(root, "rev-parse", effort.intRef), h.run.landedCommit); assert.notEqual(h.run.landedCommit, base);
  assert.equal(git(root, "rev-parse", "HEAD"), base); assert.deepEqual(readFileSync(join(root, ".git", "index")), index);
  assert.equal(existsSync(path), true); assert.equal(h.run.worktreePath, path); assert.equal(h.run.worktreeBranch, "writer");
  assert.equal(h.calls.filter(c => c === "pane close").length, 0); assert.match(readFileSync(h.run.finalPath, "utf8"), /漢🙂/);
});
