import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { join } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
import { sandboxPi } from "./helpers/tmp.ts";
import { gitTestEnv } from "./helpers/git-env.ts";
import { herdrFixture } from "./helpers/herdr-pipeline.ts";
import { createRunPipeline } from "../src/run-pipeline.ts";
import { sendToRun, availableActions } from "../src/runs.ts";
import { openEffort } from "../src/effort/open.ts";
import { addEffortMember } from "../src/effort/store.ts";
import { createWorktree } from "../src/worktree.ts";
import { SpawnQueue } from "../src/queue.ts";
sandboxPi();
const git = (cwd: string, ...args: string[]) => execFileSync("git", args, { cwd, env: gitTestEnv(), encoding: "utf8", timeout: 5000, stdio: "pipe" }).trim();

test("H8 M4/M5 owner and capacity gates precede herdr answer effects, same-owner reply integrates once", { timeout: 15000 }, async () => {
  const h = herdrFixture("ask"), cwd = h.run.cwd;
  git(cwd, "init", "-b", "main"); git(cwd, "config", "user.name", "Fixture"); git(cwd, "config", "user.email", "fixture@example.test");
  writeFileSync(join(cwd, "base"), "base"); writeFileSync(join(cwd, ".gitignore"), ".worktrees/\noracle-h7/\n");
  git(cwd, "add", "base", ".gitignore"); git(cwd, "commit", "-m", "test: base");
  const base = git(cwd, "rev-parse", "HEAD"), effort = openEffort(cwd, "h8", "owner", { verify: "git diff --check HEAD", maxParallel: 1 });
  addEffortMember(effort, h.run.id);
  const path = join(cwd, ".worktrees", "conductor-wt", h.run.id);
  createWorktree({ gitRoot: cwd, worktreePath: path, branch: "writer" }, { from: base });
  Object.assign(h.run, { parentSessionId: "owner", worktreePath: path, worktreeBranch: "writer", worktreeBaseBranch: "main",
    effort: { owner: effort.owner, name: "h8", gitRoot: cwd, cwd: path, role: "writer", spawnBase: base, touches: ["change"] } });
  new SpawnQueue(h.registry, 1, 1);
  h.onSleep(h.exit); await createRunPipeline(h.run, [], { ...h.opts, cwd: path }); h.onSleep(() => {});
  assert.equal(h.run.status, "blocked");
  const record = readFileSync(h.run.recordPath), ask = h.run.pendingAsk, calls = h.calls.length;
  const foreign = sendToRun(h.run, "Foreign answer", { registry: h.registry, timeoutMs: 4000, sessionId: "foreign" });
  assert.equal(foreign.kind, "rejected"); assert.equal(h.calls.length, calls); assert.deepEqual(readFileSync(h.run.recordPath), record);
  const blocker: import("../src/types.ts").Run = { ...h.run, id: "other", status: "running", effort: undefined, pendingAsk: undefined };
  h.registry.register(blocker);
  assert.equal(availableActions(h.run, false, "owner", h.registry).includes("send"), false);
  assert.equal(sendToRun(h.run, "No spare capacity", { registry: h.registry, timeoutMs: 4000, sessionId: "owner" }).kind, "rejected");
  assert.equal(h.calls.length, calls); assert.deepEqual(readFileSync(h.run.recordPath), record); assert.deepEqual(h.run.pendingAsk, ask);
  blocker.status = "completed";
  h.setMode("healthy");
  const sent = sendToRun(h.run, "Authorized same assignment", { registry: h.registry, timeoutMs: 4000, sessionId: "owner" });
  assert.equal(sent.kind, "started"); if (sent.kind !== "started") return;
  assert.deepEqual(h.run.pendingAsk, ask, "reservation and launch alone cannot accept the answer");
  await sent.done;
  assert.equal(h.run.status, "completed", h.run.errorMessage); assert.equal(h.run.pendingAsk, undefined);
  assert.equal(h.run.worktreePath, path); assert.equal(h.run.worktreeBranch, "writer"); assert.equal(h.run.integration?.delivery, "attempted");
  assert.equal(git(cwd, "rev-parse", "HEAD"), base);
});
